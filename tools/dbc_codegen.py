"""Generate deterministic C codecs and wire metadata from the project DBC."""

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, Iterable, List, Tuple

import cantools


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DBC = REPO_ROOT / "common" / "can_matrix.dbc"
DEFAULT_OUTPUT = REPO_ROOT / "common" / "generated"
GENERATED_FILES = (
	"can_matrix.c",
	"can_matrix.h",
	"can_matrix_meta.c",
	"can_matrix_meta.h",
)
EXPECTED_MESSAGES = {
	"ESTOP": (0x010, 2),
	"CMD": (0x100, 7),
	"TELEM": (0x180, 9),
	"HEARTBEAT": (0x1F0, 5),
	"FAULT_RECORD": (0x1F1, 16),
}
UDP_PORT_PATTERN = re.compile(r"\bUDP\s*:?[\t ]*(\d{1,5})\b", re.IGNORECASE)
TIMEOUT_PATTERN = re.compile(r"\btimeout\s+(\d+)\s*ms\b", re.IGNORECASE)
LEGAL_CAN_FD_LENGTHS = (0, 1, 2, 3, 4, 5, 6, 7, 8, 12, 16, 20, 24, 32, 48, 64)
TIMESTAMP_PATTERN = re.compile(
	r"This file was generated by cantools version [^\n]+\."
)


def _validate_database(database: Any) -> List[Tuple[Any, int, int]]:
	messages = {message.name: message for message in database.messages}
	if set(messages) != set(EXPECTED_MESSAGES):
		raise ValueError(
			"DBC message set changed; review the protocol contract before codegen: "
			f"expected {sorted(EXPECTED_MESSAGES)}, got {sorted(messages)}"
		)

	result: List[Tuple[object, int]] = []
	seen_ids = set()
	for name, (expected_id, expected_length) in EXPECTED_MESSAGES.items():
		message = messages[name]
		if message.frame_id != expected_id or message.length != expected_length:
			raise ValueError(
				f"{name} contract mismatch: expected ID/length "
				f"{expected_id:#x}/{expected_length}, got "
				f"{message.frame_id:#x}/{message.length}"
			)
		if message.frame_id > 0x7FF or message.is_extended_frame:
			raise ValueError(f"{name} must use a standard 11-bit CAN ID")
		if message.frame_id in seen_ids:
			raise ValueError(f"duplicate CAN ID {message.frame_id:#x}")
		seen_ids.add(message.frame_id)
		if message.length + 12 > 64:
			raise ValueError(f"{name} E2E data exceeds 64 bytes")

		comment = message.comment or ""
		port_match = UDP_PORT_PATTERN.search(comment)
		if port_match is None:
			raise ValueError(f"{name} DBC comment must declare its UDP port")
		udp_port = int(port_match.group(1))
		if not 1 <= udp_port <= 65535:
			raise ValueError(f"{name} has invalid UDP port {udp_port}")
		if (name == "ESTOP") != (udp_port == 5001):
			raise ValueError("only ESTOP must use UDP port 5001 in M2")
		timeout_match = TIMEOUT_PATTERN.search(comment)
		timeout_ms = int(timeout_match.group(1)) if timeout_match else 0
		if timeout_ms > 0xFFFF:
			raise ValueError(f"{name} timeout exceeds generated metadata range")

		e2e_length = message.length + 12
		wire_length = next(
			(length for length in LEGAL_CAN_FD_LENGTHS if length >= e2e_length),
			None,
		)
		if wire_length is None:
			raise ValueError(f"{name} has no legal CAN-FD wire length")
		result.append((message, udp_port, timeout_ms))

	return sorted(result, key=lambda item: item[0].frame_id)


def _render_metadata(messages: Iterable[Tuple[Any, int, int]]) -> Dict[str, str]:
	rows = []
	for message, udp_port, timeout_ms in messages:
		e2e_length = message.length + 12
		wire_length = next(length for length in LEGAL_CAN_FD_LENGTHS if length >= e2e_length)
		rows.append(
			"    { 0x%04XU, 0x%08XUL, %uU, %uU, %uU, %uU, %uU, \"%s\" },"
			% (
				message.frame_id,
				message.frame_id,
				message.length,
				e2e_length,
				wire_length,
				udp_port,
				timeout_ms,
				message.name,
			)
		)

	header = """/* Generated by tools/dbc_codegen.py; do not edit. */
#ifndef CAN_MATRIX_META_H
#define CAN_MATRIX_META_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
	uint16_t can_id;
	uint32_t data_id;
	uint8_t payload_length;
	uint8_t e2e_length;
	uint8_t wire_data_length;
	uint16_t udp_port;
	uint16_t timeout_ms;
	const char *name;
} can_matrix_message_info_t;

const can_matrix_message_info_t *can_matrix_find_message(uint16_t can_id);
size_t can_matrix_message_count(void);
const can_matrix_message_info_t *can_matrix_message_at(size_t index);

#endif /* CAN_MATRIX_META_H */
"""
	source = """/* Generated by tools/dbc_codegen.py; do not edit. */
#include \"can_matrix_meta.h\"

static const can_matrix_message_info_t messages[] = {
%s
};

size_t can_matrix_message_count(void)
{
	return sizeof(messages) / sizeof(messages[0]);
}

const can_matrix_message_info_t *can_matrix_message_at(size_t index)
{
	return (index < can_matrix_message_count()) ? &messages[index] : NULL;
}

const can_matrix_message_info_t *can_matrix_find_message(uint16_t can_id)
{
	for (size_t i = 0U; i < can_matrix_message_count(); ++i) {
		if (messages[i].can_id == can_id) {
			return &messages[i];
		}
	}
	return NULL;
}
""" % "\n".join(rows)
	return {"can_matrix_meta.h": header, "can_matrix_meta.c": source}


def _generate_files(dbc_path: Path) -> Dict[str, str]:
	database = cantools.database.load_file(str(dbc_path), strict=True)
	messages = _validate_database(database)

	with tempfile.TemporaryDirectory(prefix="m2-dbc-codegen-") as temporary_dir:
		output_dir = Path(temporary_dir)
		subprocess.run(
			[
				sys.executable,
				"-m",
				"cantools",
				"generate_c_source",
				"--database-name",
				"can_matrix",
				"--output-directory",
				str(output_dir),
				str(dbc_path),
			],
			check=True,
			stdout=subprocess.PIPE,
			stderr=subprocess.PIPE,
			universal_newlines=True,
		)
		files = {}
		for filename in ("can_matrix.c", "can_matrix.h"):
			text = (output_dir / filename).read_text(encoding="utf-8")
			text = TIMESTAMP_PATTERN.sub(
				f"This file was generated by cantools v{cantools.__version__}.",
				text,
			)
			files[filename] = text

	files.update(_render_metadata(messages))
	return files


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--dbc", type=Path, default=DEFAULT_DBC)
	parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
	parser.add_argument(
		"--check",
		action="store_true",
		help="fail if checked-in generated files do not match the DBC",
	)
	args = parser.parse_args()
	dbc_path = args.dbc.resolve()
	output_dir = args.output_dir.resolve()

	if not dbc_path.is_file():
		parser.error(f"DBC file not found: {dbc_path}")

	try:
		generated = _generate_files(dbc_path)
	except (OSError, ValueError, subprocess.CalledProcessError) as error:
		print(f"DBC code generation failed: {error}", file=sys.stderr)
		return 1

	if args.check:
		stale = [
			filename
			for filename in GENERATED_FILES
			if not (output_dir / filename).is_file()
			or (output_dir / filename).read_text(encoding="utf-8") != generated[filename]
		]
		if stale:
			print("Generated DBC files are stale: " + ", ".join(stale), file=sys.stderr)
			return 1
		print(f"DBC generated files are up to date (cantools {cantools.__version__}).")
		return 0

	output_dir.mkdir(parents=True, exist_ok=True)
	for filename, text in generated.items():
		with (output_dir / filename).open("w", encoding="utf-8", newline="\n") as output_file:
			output_file.write(text)
	print(f"Generated {len(generated)} deterministic files in {output_dir}.")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
